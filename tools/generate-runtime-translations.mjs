#!/usr/bin/env node

import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const domain = "plasma_applet_pp.ua.xxanqw.justweather"
const languages = [
    { locale: "uk", pluralForms: 3 },
    { locale: "zh_CN", pluralForms: 1 },
    { locale: "ar", pluralForms: 6 },
    { locale: "fr", pluralForms: 2 },
    { locale: "es", pluralForms: 2 }
]

function decodePoString(value, file, lineNumber) {
    try {
        return JSON.parse(value)
    } catch (error) {
        throw new Error(`${file}:${lineNumber}: invalid PO string: ${error.message}`)
    }
}

function parsePo(file) {
    const lines = fs.readFileSync(file, "utf8").split(/\r?\n/)
    const entries = []
    let entry = null
    let activeField = null
    let fuzzy = false

    function ensureEntry() {
        if (!entry) {
            entry = { msgid: null, msgidPlural: null, msgstr: [] }
        }
    }

    function finishEntry() {
        if (entry && entry.msgid !== null) {
            entry.fuzzy = fuzzy
            entries.push(entry)
        }
        entry = null
        activeField = null
        fuzzy = false
    }

    function setField(field, index, value) {
        ensureEntry()
        if (field === "msgstr") {
            entry.msgstr[index] = value
        } else {
            entry[field] = value
        }
        activeField = { field, index }
    }

    for (let index = 0; index < lines.length; index++) {
        const line = lines[index]

        if (line === "") {
            finishEntry()
            continue
        }
        if (line.startsWith("#,")) {
            fuzzy ||= line.split(",").some(flag => flag.trim() === "fuzzy")
            continue
        }
        if (line.startsWith("#")) {
            continue
        }

        let match = line.match(/^msgid (".*")$/)
        if (match) {
            setField("msgid", 0, decodePoString(match[1], file, index + 1))
            continue
        }
        match = line.match(/^msgid_plural (".*")$/)
        if (match) {
            setField("msgidPlural", 0, decodePoString(match[1], file, index + 1))
            continue
        }
        match = line.match(/^msgstr(?:\[(\d+)\])? (".*")$/)
        if (match) {
            setField("msgstr", Number(match[1] || 0),
                     decodePoString(match[2], file, index + 1))
            continue
        }
        match = line.match(/^(".*")$/)
        if (match && activeField) {
            const value = decodePoString(match[1], file, index + 1)
            if (activeField.field === "msgstr") {
                entry.msgstr[activeField.index] += value
            } else {
                entry[activeField.field] += value
            }
            continue
        }

        throw new Error(`${file}:${index + 1}: unsupported PO syntax: ${line}`)
    }

    finishEntry()
    return entries
}

function placeholders(message) {
    return [...new Set(message.match(/%[1-9]/g) || [])].sort().join(",")
}

function loadCatalog(language) {
    const file = path.join(rootDir, "package", "translate", language.locale,
                           "LC_MESSAGES", `${domain}.po`)
    const catalog = {}

    for (const entry of parsePo(file)) {
        if (!entry.msgid || entry.fuzzy) {
            continue
        }

        const expectedForms = entry.msgidPlural ? language.pluralForms : 1
        const forms = entry.msgstr.slice(0, expectedForms)
        if (forms.length !== expectedForms || forms.some(value => !value)) {
            throw new Error(`${file}: incomplete translation for ${JSON.stringify(entry.msgid)}`)
        }

        const sourcePlaceholders = placeholders(entry.msgidPlural || entry.msgid)
        for (const translation of forms) {
            const translatedPlaceholders = placeholders(translation)
            const invalidPlaceholders = translatedPlaceholders.split(",")
                .filter(value => value && !sourcePlaceholders.split(",").includes(value))
            if (invalidPlaceholders.length
                    || (!entry.msgidPlural
                        && translatedPlaceholders !== sourcePlaceholders)) {
                throw new Error(`${file}: placeholder mismatch for ${JSON.stringify(entry.msgid)}`)
            }
        }

        catalog[entry.msgid] = forms
    }

    return catalog
}

const catalogs = Object.fromEntries(
    languages.map(language => [language.locale, loadCatalog(language)])
)
const outputFile = path.join(rootDir, "package", "contents", "ui",
                             "GeneratedTranslations.js")
const output = `.pragma library

// Generated from package/translate/*/LC_MESSAGES/${domain}.po.
// Run tools/update-translations.sh after editing a PO file. Do not edit this file.

var catalogs = ${JSON.stringify(catalogs, null, 4)}

function substitute(message, args) {
    var result = message
    for (var index = 0; index < args.length; index++) {
        if (args[index] !== undefined) {
            result = result.split("%" + (index + 1)).join(args[index])
        }
    }
    return result
}

function pluralIndex(locale, count) {
    if (locale === "zh_CN") return 0
    if (locale === "uk") {
        return count % 10 === 1 && count % 100 !== 11
            ? 0
            : count % 10 >= 2 && count % 10 <= 4
                && (count % 100 < 12 || count % 100 > 14) ? 1 : 2
    }
    if (locale === "ar") {
        return count === 0 ? 0
            : count === 1 ? 1
            : count === 2 ? 2
            : count % 100 >= 3 && count % 100 <= 10 ? 3
            : count % 100 >= 11 && count % 100 <= 99 ? 4 : 5
    }
    if (locale === "fr") return count > 1 ? 1 : 0
    return count === 1 ? 0 : 1
}

function translate(locale, message, args) {
    var forms = catalogs[locale] && catalogs[locale][message]
    return substitute(forms ? forms[0] : message, args || [])
}

function translatePlural(locale, singular, plural, count) {
    var forms = catalogs[locale] && catalogs[locale][singular]
    var message = forms ? forms[pluralIndex(locale, count)]
                        : (count === 1 ? singular : plural)
    return substitute(message || plural, [count])
}
`

fs.writeFileSync(outputFile, output)
console.log(`Generated ${path.relative(rootDir, outputFile)}`)
