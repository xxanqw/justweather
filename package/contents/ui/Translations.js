function languageForLocale(localeName) {
    var normalized = (localeName || "").toLowerCase().replace("_", "-")
    var language = normalized.split("-")[0]

    if (language === "en") return 1
    if (language === "uk") return 2
    if (language === "ru") return 2
    if (language === "zh") return 3
    if (language === "ar") return 4
    if (language === "fr") return 5
    if (language === "es") return 6
    return 0
}

