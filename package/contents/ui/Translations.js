function effectiveLocaleName(language, systemLocaleName) {
    if (language !== 0) {
        return localeName(language)
    }

    var systemLanguage = (systemLocaleName || "").toLowerCase()
        .replace("_", "-").split("-")[0]
    return systemLanguage === "ru" ? localeName(2) : systemLocaleName
}

function isRightToLeft(language, systemLocaleName) {
    var effective = language === 0 ? languageForLocale(systemLocaleName) : language
    return effective === 4
}

function substitute(message, args) {
    var result = message
    for (var i = 0; i < args.length; i++) {
        if (args[i] !== undefined) {
            result = result.split("%" + (i + 1)).join(args[i])
        }
    }
    return result
}

function translate(language, message, args) {
    var languageTranslations = translations[language]
    var translated = languageTranslations && languageTranslations[message]
        ? languageTranslations[message]
        : message
    return substitute(translated, args || [])
}

function translatePlural(language, singular, plural, count) {
    if (language === 2) {
        var lastDigit = count % 10
        var lastTwoDigits = count % 100
        if (lastDigit >= 2 && lastDigit <= 4
                && (lastTwoDigits < 12 || lastTwoDigits > 14)
                && ukrainianFew[plural]) {
            return substitute(ukrainianFew[plural], [count])
        }
    }

    if (language === 4 && count === 2 && arabicDual[plural]) {
        return substitute(arabicDual[plural], [count])
    }
    if (language === 4 && count > 10 && arabicMany[plural]) {
        return substitute(arabicMany[plural], [count])
    }

    var source = count === 1 ? singular : plural
    return translate(language, source, [count])
}
